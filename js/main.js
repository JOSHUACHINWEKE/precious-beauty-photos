/**
 * Precious Beauty Photos — site behavior.
 *
 * Structure: one small module per feature, each with an init() entry
 * point. Nothing runs until App.init() fires on DOMContentLoaded, and
 * modules don't reach into each other — they only touch their own bit
 * of the DOM. Business data (FAQs, portfolio categories, WhatsApp
 * number, etc.) lives in config.js, not here.
 */
(function () {
  'use strict';

  /* =====================================================================
     PortfolioGrid — builds the 100+ placeholder frames on the Portfolio
     page from SITE_CONFIG.portfolio, so the HTML doesn't hand-list them.
     ===================================================================== */
  const PortfolioGrid = {
    init() {
      const grid = document.getElementById('portfolioGrid');
      if (!grid) return;

      const { categories } = SITE_CONFIG.portfolio;
      const aspectRatioClasses = ['g-tall', 'g-wide', 'g-square'];

      let html = '';
      let totalItems = 0;

      categories.forEach(category => {
        const items = category.items || (category.images || []).map((src, index) => ({
          type: 'image',
          src,
          title: category.spots[index % category.spots.length]
        }));

        items.forEach((item, index) => {
          const number = String(index + 1).padStart(3, '0');
          const title = item.title || category.name;
          const aspect = aspectRatioClasses[totalItems % aspectRatioClasses.length];

          html += this.renderFrame({ category, item, title, number, aspect });
          totalItems++;
        });
      });

      grid.innerHTML = html;
      this.renderCount(totalItems);
    },

    renderFrame({ category, item, title, number, aspect }) {
      const caption = `${category.name} — ${title}`;

      if (item.type === 'video') {
        return `
          <button
            type="button"
            class="frame video-card ${aspect} reveal"
            data-cat="${category.key}"
            data-video-src="${item.src}"
            data-video-title="${caption}"
            aria-label="Play ${caption}"
          >
            <img class="frame-photo" src="${item.poster}" alt="${caption}">
            <span class="video-shade"></span>
            <span class="video-play" aria-hidden="true">▶</span>
            <span class="video-kicker">WATCH FILM</span>
            <div class="cap">
              <span>${category.label}&middot;${number}</span>
              <b>${title}</b>
            </div>
          </button>
        `;
      }

      if (item.type === 'placeholder') {
        return `
          <div
            class="frame portfolio-placeholder ${aspect} reveal"
            data-cat="${category.key}"
            data-caption="${caption}"
          >
            <div class="placeholder-inner">
              <span class="placeholder-mark">✦</span>
              <span class="placeholder-label">${category.name}</span>
              <strong>${title}</strong>
              <small>Coming Soon</small>
            </div>
            <div class="cap">
              <span>${category.label}&middot;${number}</span>
              <b>${title}</b>
            </div>
          </div>
        `;
      }

      return `
        <div
          class="frame ${aspect} reveal"
          data-cat="${category.key}"
          data-caption="${caption}"
        >
          <img class="frame-photo" src="${item.src}" alt="${caption}">
          <div class="cap">
            <span>${category.label}&middot;${number}</span>
            <b>${title}</b>
          </div>
        </div>
      `;
    },

    renderCount(total) {
      const countEl = document.getElementById('portfolioCount');
      if (countEl) countEl.textContent = `${total} projects in the collection.`;
    }
  };

  /* =====================================================================
     PortfolioFilters — category filter buttons on the Portfolio page.
     Reads data-cat attributes generated by PortfolioGrid above.
     ===================================================================== */
  const PortfolioFilters = {
    init() {
      const buttons = document.querySelectorAll('.filter-btn');
      if (!buttons.length) return;

      buttons.forEach(btn => {
        btn.addEventListener('click', () => this.apply(btn, buttons));
      });
    },

    apply(activeBtn, allButtons) {
      allButtons.forEach(b => b.classList.remove('active'));
      activeBtn.classList.add('active');

      const filter = activeBtn.dataset.filter;
      document.querySelectorAll('#portfolioGrid .frame').forEach(card => {
        const matches = filter === 'all' || card.dataset.cat === filter;
        card.style.display = matches ? '' : 'none';
      });
    }
  };

  /* =====================================================================
     FaqAccordion — renders SITE_CONFIG.faqs into any container and wires
     up expand/collapse. Used on both the Home and Contact pages.
     ===================================================================== */
  const FaqAccordion = {
    init() {
      this.renderInto('faqList');
      this.renderInto('faqListContact');
    },

    renderInto(containerId) {
      const el = document.getElementById(containerId);
      if (!el) return;

      el.innerHTML = SITE_CONFIG.faqs.map((faq, i) => `
        <div class="faq-item">
          <button class="faq-q" data-idx="${i}-${containerId}">
            <span>${faq.q}</span><span class="plus">+</span>
          </button>
          <div class="faq-a"><p>${faq.a}</p></div>
        </div>
      `).join('');

      el.querySelectorAll('.faq-q').forEach(btn => {
        btn.addEventListener('click', () => this.toggle(btn));
      });
    },

    toggle(btn) {
      const item = btn.closest('.faq-item');
      const answer = item.querySelector('.faq-a');
      const isOpen = item.classList.contains('open');

      item.classList.toggle('open', !isOpen);
      answer.style.maxHeight = isOpen ? null : answer.scrollHeight + 'px';
    }
  };

  /* =====================================================================
     PageRouter — single-page navigation between Home / Portfolio / About
     / Contact. Swaps which <main id="page-*"> is visible and keeps the
     URL hash + active nav link in sync.
     ===================================================================== */
  const PageRouter = {
    init() {
      this.pages = document.querySelectorAll('.page');
      this.navLinks = document.querySelectorAll('nav.links a[data-page]');
      const allDataPageLinks = document.querySelectorAll('a[data-page]');

      allDataPageLinks.forEach(link => {
        link.addEventListener('click', (e) => {
          e.preventDefault();
          const name = link.dataset.page;
          history.replaceState(null, '', '#' + name);
          this.show(name);
        });
      });

      const requested = (location.hash || '#home').replace('#', '');
      const initial = SITE_CONFIG.pages.includes(requested) ? requested : 'home';
      this.show(initial);
    },

    show(name) {
      this.pages.forEach(p => p.classList.remove('active'));

      const target = document.getElementById('page-' + name);
      if (!target) return;

      // Force a reflow so the CSS entrance animation replays every time,
      // not just on the very first page load.
      void target.offsetWidth;
      target.classList.add('active');

      this.navLinks.forEach(a => a.classList.toggle('active', a.dataset.page === name));
      window.scrollTo(0, 0);

      const navLinksContainer = document.getElementById('navLinks');
      if (navLinksContainer) navLinksContainer.classList.remove('open');
    }
  };

  /* =====================================================================
     MobileNav — hamburger toggle for the collapsed nav menu (<900px).
     ===================================================================== */
  const MobileNav = {
    init() {
      const toggle = document.getElementById('menuToggle');
      const links = document.getElementById('navLinks');
      if (!toggle || !links) return;

      toggle.addEventListener('click', () => links.classList.toggle('open'));
    }
  };

  /* =====================================================================
     ContactForm — builds a WhatsApp "click to chat" link from the form
     fields and opens it, rather than submitting to a backend (this is a
     static site with no server to receive the form).
     ===================================================================== */
  const ContactForm = {
    init() {
      const form = document.getElementById('contactForm');
      if (!form) return;

      form.addEventListener('submit', (e) => {
        e.preventDefault();
        this.sendViaWhatsApp(form);
      });
    },

    sendViaWhatsApp(form) {
      const message = this.buildMessage({
        name: form.querySelector('#name').value.trim(),
        email: form.querySelector('#email').value.trim(),
        sessionType: form.querySelector('#sessionType').value,
        date: form.querySelector('#date').value,
        details: form.querySelector('#message').value.trim()
      });

      const url = `https://wa.me/${SITE_CONFIG.whatsappNumber}?text=${encodeURIComponent(message)}`;
      window.open(url, '_blank', 'noopener');

      const note = document.getElementById('formNote');
      if (note) note.classList.add('show');
    },

    buildMessage({ name, email, sessionType, date, details }) {
      let text = `Hi Precious Beauty Photos! I'd like to inquire about a project.\n\n`;
      text += `Name: ${name}\n`;
      text += `Email: ${email}\n`;
      text += `Service Type: ${sessionType}\n`;
      if (date) text += `Preferred Date: ${date}\n`;
      if (details) text += `Details: ${details}\n`;
      return text;
    }
  };

  /* =====================================================================
     BookingWidget — points the "Book & Pay Now" button at the real
     Square Appointments URL from config, once one is set.
     ===================================================================== */
  const BookingWidget = {
    init() {
      const link = document.getElementById('bookNowLink');
      if (link && SITE_CONFIG.bookingUrl) {
        link.href = SITE_CONFIG.bookingUrl;
      }
    }
  };

  /* =====================================================================
     VideoModal — opens portfolio films in a focused popup player.
     ===================================================================== */
  const VideoModal = {
    init() {
      this.modal = document.getElementById('videoModal');
      this.player = document.getElementById('videoModalPlayer');
      this.title = document.getElementById('videoModalTitle');
      this.closeButton = document.getElementById('videoModalClose');

      if (!this.modal || !this.player) return;

      document.addEventListener('click', (event) => {
        const card = event.target.closest('.video-card');
        if (card) this.open(card);
      });

      if (this.closeButton) this.closeButton.addEventListener('click', () => this.close());
      this.modal.addEventListener('click', (event) => {
        if (event.target === this.modal) this.close();
      });

      document.addEventListener('keydown', (event) => {
        if (event.key === 'Escape' && this.modal.classList.contains('open')) this.close();
      });
    },

    open(card) {
      this.player.src = card.dataset.videoSrc;
      if (this.title) this.title.textContent = card.dataset.videoTitle || 'Video';
      this.modal.classList.add('open');
      this.modal.setAttribute('aria-hidden', 'false');
      document.body.classList.add('modal-open');
      this.player.play().catch(() => {});
    },

    close() {
      this.player.pause();
      this.player.removeAttribute('src');
      this.player.load();
      this.modal.classList.remove('open');
      this.modal.setAttribute('aria-hidden', 'true');
      document.body.classList.remove('modal-open');
    }
  };

  /* =====================================================================
     ScrollReveal — fades/slides .reveal elements in as they enter the
     viewport. No-ops (shows everything immediately) if the visitor has
     requested reduced motion.
     ===================================================================== */
  const ScrollReveal = {
    init() {
      const prefersMotion = window.matchMedia('(prefers-reduced-motion: no-preference)').matches;
      const elements = document.querySelectorAll('.reveal');

      if (!prefersMotion) {
        elements.forEach(el => el.classList.add('in'));
        return;
      }

      const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
          if (entry.isIntersecting) {
            entry.target.classList.add('in');
            observer.unobserve(entry.target);
          }
        });
      }, { threshold: 0.15 });

      elements.forEach(el => observer.observe(el));
    }
  };

  /* =====================================================================
     App — bootstraps every module in a predictable order.
     ===================================================================== */
  const App = {
    init() {
      PortfolioGrid.init();     // must run before PortfolioFilters & ScrollReveal
      PortfolioFilters.init();
      FaqAccordion.init();
      PageRouter.init();
      MobileNav.init();
      ContactForm.init();
      BookingWidget.init();
      VideoModal.init();
      ScrollReveal.init();      // must run after PortfolioGrid so new .reveal items are caught
    }
  };

  document.addEventListener('DOMContentLoaded', () => App.init());
})();
